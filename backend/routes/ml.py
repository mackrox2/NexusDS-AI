def create_preprocessor(X, algorithm):















    """















    Build a robust preprocessing pipeline.































    Completely empty feature columns are removed before they reach sklearn















    imputers. SimpleImputer cannot calculate a most_frequent/median value for















    a column containing zero observed values, which otherwise produces noisy















    sklearn warnings and can make the transformed feature set inconsistent.































    Returns:















        preprocessor, numeric_features, categorical_features















    """















    X = X.copy()































    # Remove columns that contain no observed values at all.















    # This is intentionally done only on feature columns, never on the target.















    empty_columns = [















        col for col in X.columns















        if X[col].notna().sum() == 0















    ]































    if empty_columns:















        print(















            "ML DROPPED COMPLETELY EMPTY FEATURES:",















            [str(col) for col in empty_columns]















        )















        X = X.drop(columns=empty_columns)































    numeric, categorical = [], []































    for col in X.columns:















        if is_numeric_series(X[col]):















            numeric.append(col)















            X[col] = numeric_convert(X[col])















        else:















            categorical.append(col)































    transformers = []































    numeric_steps = [















        ("imputer", SimpleImputer(strategy="median"))















    ]































    if algorithm in {"logistic_regression", "knn", "linear_regression"}:















        numeric_steps.append(("scaler", StandardScaler()))































    if numeric:















        transformers.append(















            ("numeric", Pipeline(steps=numeric_steps), numeric)















        )































    if categorical:















        categorical_pipeline = Pipeline(steps=[















            ("imputer", SimpleImputer(strategy="most_frequent")),















            (















                "onehot",















                OneHotEncoder(















                    handle_unknown="ignore",















                    sparse_output=False















                )















            )















        ])































        transformers.append(















            ("categorical", categorical_pipeline, categorical)















        )































    if not transformers:















        raise HTTPException(















            400,















            "No usable feature columns were found after removing empty columns."















        )































    return (















        ColumnTransformer(















            transformers=transformers,















            remainder="drop"















        ),















        numeric,















        categorical















    )















































def model_specs(problem_type):















    if problem_type == "classification":















        return {















            "random_forest": RandomForestClassifier(n_estimators=180, random_state=42, n_jobs=-1, class_weight="balanced"),















            "logistic_regression": LogisticRegression(max_iter=2500),















            "decision_tree": DecisionTreeClassifier(random_state=42, class_weight="balanced"),















            "knn": KNeighborsClassifier(n_neighbors=5)















        }















    return {















        "random_forest": RandomForestRegressor(n_estimators=180, random_state=42, n_jobs=-1),















        "linear_regression": LinearRegression(),















        "decision_tree": DecisionTreeRegressor(random_state=42)















    }















































def build_pipeline(X_train, problem_type, algorithm):















    # Work on a copy so preprocessing never mutates the caller's dataframe.















    X_train = X_train.copy()































    # Keep the exact feature set that the preprocessor will use.















    empty_columns = [















        col for col in X_train.columns















        if X_train[col].notna().sum() == 0















    ]















    if empty_columns:















        X_train = X_train.drop(columns=empty_columns)































    preprocessor, numeric, categorical = create_preprocessor(















        X_train,















        algorithm















    )















    model = model_specs(problem_type).get(algorithm)















    if model is None:















        raise HTTPException(400, f"'{algorithm}' is not available for {problem_type}.")















    return Pipeline([("preprocessor", preprocessor), ("model", model)]), numeric, categorical















































def evaluate(pipeline, X_test, y_test, problem_type):















    pred = pipeline.predict(X_test)































    if problem_type == "classification":















        return {















            "accuracy": round(float(accuracy_score(y_test, pred)), 4),















            "precision": round(float(precision_score(y_test, pred, average="weighted", zero_division=0)), 4),















            "recall": round(float(recall_score(y_test, pred, average="weighted", zero_division=0)), 4),















            "f1Score": round(float(f1_score(y_test, pred, average="weighted", zero_division=0)), 4)















        }, pred































    mse = mean_squared_error(y_test, pred)















    return {















        "r2Score": round(float(r2_score(y_test, pred)), 4),















        "mae": round(float(mean_absolute_error(y_test, pred)), 4),















        "mse": round(float(mse), 4),















        "rmse": round(float(np.sqrt(mse)), 4)















    }, pred















































def get_feature_importance(pipeline, top_n=12):







    try:







        model=pipeline.named_steps["model"]; prep=pipeline.named_steps["preprocessor"]; names=prep.get_feature_names_out()







        if hasattr(model,"feature_importances_"): vals=np.asarray(model.feature_importances_,dtype=float)







        elif hasattr(model,"coef_"):







            coef=np.asarray(model.coef_,dtype=float); vals=np.mean(np.abs(coef),axis=0) if coef.ndim>1 else np.abs(coef)







        else: return []







        items=[{"feature":str(n).replace("numeric__","").replace("categorical__",""),"importance":round(float(v),5)} for n,v in zip(names,vals)]







        return sorted(items,key=lambda x:x["importance"],reverse=True)[:top_n]







    except Exception as error:







        print("FEATURE IMPORTANCE WARNING:",repr(error)); return []























def build_feature_defaults(X, numeric_features, categorical_features):



    defaults = {}



    for col in numeric_features:



        values = numeric_convert(X[col]).dropna()



        defaults[str(col)] = safe_number(values.median()) if not values.empty else 0



    for col in categorical_features:



        values = X[col].dropna().astype(str).str.strip()



        defaults[str(col)] = str(values.mode().iloc[0]) if not values.empty and not values.mode().empty else ""



    return defaults











def cross_validation_score(X_train, y_train, problem_type, algorithm):















    """















    Use CV for model selection when the dataset supports it.















    This avoids choosing a model from a single lucky/unlucky split.















    """















    try:















        if problem_type == "classification":















            counts = pd.Series(y_train).value_counts()















            min_class = int(counts.min())















            n_splits = min(5, min_class)































            if n_splits < 2:















                return None, "Insufficient samples per class for cross-validation."































            splitter = StratifiedKFold(















                n_splits=n_splits,















                shuffle=True,















                random_state=42















            )















            scoring = {















                "accuracy": "accuracy",















                "precision": "precision_weighted",















                "recall": "recall_weighted",















                "f1": "f1_weighted"















            }















        else:















            n_splits = min(5, len(X_train))















            if n_splits < 2:















                return None, "Insufficient rows for cross-validation."































            splitter = KFold(















                n_splits=n_splits,















                shuffle=True,















                random_state=42















            )















            scoring = {















                "r2": "r2",















                "mae": "neg_mean_absolute_error",















                "rmse": "neg_root_mean_squared_error"















            }































        pipeline, _, _ = build_pipeline(X_train, problem_type, algorithm)































        scores = cross_validate(















            pipeline,















            X_train,















            y_train,















            cv=splitter,















            scoring=scoring,















            error_score="raise"















        )































        if problem_type == "classification":















            cv_metrics = {















                "accuracy": round(float(np.mean(scores["test_accuracy"])), 4),















                "precision": round(float(np.mean(scores["test_precision"])), 4),















                "recall": round(float(np.mean(scores["test_recall"])), 4),















                "f1Score": round(float(np.mean(scores["test_f1"])), 4)















            }















            return cv_metrics, f"{n_splits}-fold stratified cross-validation"















        else:















            cv_metrics = {















                "r2Score": round(float(np.mean(scores["test_r2"])), 4),















                "mae": round(float(-np.mean(scores["test_mae"])), 4),















                "rmse": round(float(-np.mean(scores["test_rmse"])), 4)















            }















            return cv_metrics, f"{n_splits}-fold cross-validation"































    except Exception as error:















        print(f"CV {algorithm} FAILED:", repr(error))















        return None, f"Cross-validation unavailable: {error}"















































def tuning_grid(problem_type, algorithm):







    if problem_type == "classification":







        return {"random_forest":{"model__n_estimators":[120,180],"model__max_depth":[None,12]},"logistic_regression":{"model__C":[0.5,1.0,2.0]},"decision_tree":{"model__max_depth":[None,8,14]},"knn":{"model__n_neighbors":[3,5,7]}}.get(algorithm,{})







    return {"random_forest":{"model__n_estimators":[120,180],"model__max_depth":[None,12]},"decision_tree":{"model__max_depth":[None,8,14]}}.get(algorithm,{})















def tune_pipeline(pipeline,X,y,problem_type,algorithm):







    grid=tuning_grid(problem_type,algorithm)







    if not grid: return pipeline,{"enabled":True,"performed":False,"reason":"No tuning grid is defined for this algorithm."}







    if problem_type=="classification":







        min_class=int(pd.Series(y).value_counts().min()); cv=min(3,min_class)







        if cv<2: return pipeline,{"enabled":True,"performed":False,"reason":"Insufficient samples per class for tuning."}







        splitter=StratifiedKFold(n_splits=cv,shuffle=True,random_state=42); scoring="f1_weighted"







    else:







        cv=min(3,len(X))







        if cv<2: return pipeline,{"enabled":True,"performed":False,"reason":"Insufficient rows for tuning."}







        splitter=KFold(n_splits=cv,shuffle=True,random_state=42); scoring="r2"







    search=GridSearchCV(pipeline,grid,scoring=scoring,cv=splitter,n_jobs=-1,error_score="raise"); search.fit(X,y)







    return search.best_estimator_,{"enabled":True,"performed":True,"cv":cv,"scoring":scoring,"bestScore":safe_number(search.best_score_),"bestParams":{str(k):v for k,v in search.best_params_.items()}}















