def detect_excel_header(file_path):















    try:















        preview = pd.read_excel(file_path, header=None, nrows=20)















    except Exception:















        return 0































    keywords = [















        "s.no", "sr.no", "serial", "date", "city", "name", "id",















        "total", "amount", "value", "status", "approved", "approval",















        "pending", "cancel", "done", "received", "completed",















        "customer", "product", "price", "sales", "profit", "target"















    ]































    best_row, best_score = 0, -1e9















    for row_index in range(len(preview)):















        values = []















        keyword_score = 0















        for value in preview.iloc[row_index]:















            if pd.isna(value):















                continue















            text = str(value).strip()















            if not text or text.lower().startswith("unnamed"):















                continue















            values.append(text)















            if any(k in text.lower() for k in keywords):















                keyword_score += 2































        if not values:















            continue































        score = len(values) + len(set(v.lower() for v in values)) * 0.25 + keyword_score















        if len(values) <= 2:















            score -= 4































        if score > best_score:















            best_score, best_row = score, row_index































    return best_row















































def clean_dataframe(df):















    df = df.copy()















    df = df.dropna(axis=0, how="all").dropna(axis=1, how="all")































    columns = []















    seen = {}















    for i, col in enumerate(df.columns):















        name = normalize_column_name(col)















        if not name or name.lower().startswith("unnamed"):















            name = f"Column_{i + 1}"















        if name in seen:















            seen[name] += 1















            name = f"{name}_{seen[name]}"















        else:















            seen[name] = 1















        columns.append(name)















    df.columns = columns































    for col in df.columns:















        if df[col].dtype == object:















            df[col] = df[col].map(lambda x: x.strip() if isinstance(x, str) else x)















            df[col] = df[col].map(















                lambda x: np.nan















                if isinstance(x, str) and x.strip().lower() in {















                    "", "na", "n/a", "null", "none", "nan", "-", "--",















                    "missing", "not available", "not applicable"















                }















                else x















            )















    return df















































