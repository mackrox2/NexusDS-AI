def compare_models(X_train,X_test,y_train,y_test,problem_type,requested_algorithm,tune=False):







    specs=model_specs(problem_type); algos=list(specs.keys()) if requested_algorithm=="auto" else [requested_algorithm]; results=[]; trained={}







    for algorithm in algos:







        try:







            pipe,num,cat=build_pipeline(X_train,problem_type,algorithm); tuning={"enabled":bool(tune),"performed":False,"reason":"Tuning disabled."}







            if tune: pipe,tuning=tune_pipeline(pipe,X_train,y_train,problem_type,algorithm)







            pipe.fit(X_train,y_train); metrics,pred=evaluate(pipe,X_test,y_test,problem_type); diagnostics=evaluation_diagnostics(pipe,X_test,y_test,problem_type,pred); cv_metrics,cv_method=cross_validation_score(X_train,y_train,problem_type,algorithm)







            score=cv_metrics["f1Score"] if problem_type=="classification" and cv_metrics else metrics["f1Score"] if problem_type=="classification" else cv_metrics["r2Score"] if cv_metrics else metrics["r2Score"]







            results.append({"algorithm":algorithm,"metrics":metrics,"diagnostics":diagnostics,"cvMetrics":cv_metrics,"selectionScore":round(float(score),4),"score":round(float(score),4),"cvMethod":cv_method,"selectionMetric":"f1Score" if problem_type=="classification" else "r2Score","tuning":tuning,"status":"success"}); trained[algorithm]=(pipe,num,cat,pred,diagnostics,tuning)







        except Exception as error:







            print(f"MODEL {algorithm} FAILED:",repr(error)); results.append({"algorithm":algorithm,"metrics":{},"diagnostics":{},"cvMetrics":None,"selectionScore":None,"score":None,"cvMethod":None,"tuning":{"enabled":bool(tune),"performed":False},"status":"failed","error":str(error)})







    ok=[r for r in results if r["status"]=="success"]







    if not ok: raise HTTPException(400,"All candidate models failed. "+"; ".join(f"{r['algorithm']}: {r.get('error','failed')}" for r in results))







    best=max(ok,key=lambda r:r["selectionScore"]); return best,results,trained[best["algorithm"]],trained























