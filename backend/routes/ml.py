    try:







        a=np.asarray(y,dtype=float); q=np.asarray(pred,dtype=float); r=a-q







        d.update({"residualMean":round(float(np.mean(r)),4),"residualStd":round(float(np.std(r)),4),"residualMae":round(float(np.mean(np.abs(r))),4)})







        d["predictionSample"]=[{"actual":safe_number(a[i]),"predicted":safe_number(q[i]),"residual":safe_number(r[i])} for i in range(min(300,len(a)))]







    except Exception as error: d["diagnosticWarning"]=str(error)







    return d















