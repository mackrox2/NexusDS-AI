@router.post("/explain")
def explain_model_prediction(payload: dict, current_user=Depends(get_current_user)):
    """
    Explain one prediction using baseline replacement.

    If the caller does not provide a row, model feature defaults are used as
    a stable baseline/representative row. Each feature contribution is the
    change in the model output when that feature is moved from the supplied
    value back to its learned baseline value.

    This is model-agnostic and works with the same persisted pipeline used by
    Prediction Studio and Batch Prediction.
    """
    dataset_id = str(payload.get("datasetId", "")).strip()
    model_id = str(payload.get("modelId", "")).strip()
    supplied_row = payload.get("row")

    if not dataset_id or not model_id:
        raise HTTPException(400, "datasetId and modelId are required.")

    if supplied_row is not None and not isinstance(supplied_row, dict):
        raise HTTPException(400, "row must be an object.")

    doc = get_dataset_document(dataset_id, current_user)
    metadata = doc.get("lastMLTraining") or {}

    if str(metadata.get("modelId", "")) != model_id:
        raise HTTPException(404, "This model is not the latest trained model for the selected dataset.")

    pipeline = load_model_artifact(current_user, model_id)

    feature_columns = [str(c) for c in (metadata.get("featureColumns") or [])]
    feature_defaults = metadata.get("featureDefaults") or {}
    problem_type = str(metadata.get("problemType") or "classification").lower()
    target_classes = metadata.get("targetClasses") or []

    if not feature_columns:
        raise HTTPException(400, "The trained model has no stored feature schema.")

    source_row = dict(supplied_row or {})
    normalized_row = {}

    for column in feature_columns:
        if column in source_row and source_row[column] not in (None, ""):
            normalized_row[column] = source_row[column]
        elif column in feature_defaults:
            normalized_row[column] = feature_defaults[column]
        else:
            normalized_row[column] = None

    frame = pd.DataFrame([normalized_row], columns=feature_columns)

    try:
        prediction_raw = pipeline.predict(frame)[0]

        def prediction_label(value):
            if problem_type == "classification" and target_classes:
                try:
                    idx = int(value)
                    if 0 <= idx < len(target_classes):
                        return str(target_classes[idx])
                except Exception:
                    pass
            return safe_number(value) if isinstance(value, (int, float, np.integer, np.floating)) else str(value)

        def output_value(dataframe, class_index=None):
            if problem_type == "classification" and hasattr(pipeline, "predict_proba"):
                probabilities = pipeline.predict_proba(dataframe)
                classes = getattr(pipeline.named_steps.get("model"), "classes_", [])
                if class_index is None:
                    raw_prediction = pipeline.predict(dataframe)[0]
                    try:
                        class_index = list(classes).index(raw_prediction)
                    except Exception:
                        class_index = 0
                class_index = max(0, min(int(class_index), probabilities.shape[1] - 1))
                return float(probabilities[0][class_index]), "probability"
            value = pipeline.predict(dataframe)[0]
            return float(value), "prediction"

        predicted_class_index = None
        if problem_type == "classification" and hasattr(pipeline, "predict_proba"):
            classes = getattr(pipeline.named_steps.get("model"), "classes_", [])
            try:
                predicted_class_index = list(classes).index(prediction_raw)
            except Exception:
                predicted_class_index = 0

        full_output, output_kind = output_value(frame, predicted_class_index)

        baseline_row = {
            column: feature_defaults.get(column, normalized_row.get(column))
            for column in feature_columns
        }
        baseline_frame = pd.DataFrame([baseline_row], columns=feature_columns)
        baseline_output, _ = output_value(baseline_frame, predicted_class_index)

        contributions = []

        for column in feature_columns:
            changed_row = dict(normalized_row)
            changed_row[column] = feature_defaults.get(column, normalized_row.get(column))
            changed_frame = pd.DataFrame([changed_row], columns=feature_columns)

            try:
                changed_output, _ = output_value(changed_frame, predicted_class_index)
                contribution = full_output - changed_output
            except Exception:
                continue

            raw_value = normalized_row.get(column)
            baseline_value = baseline_row.get(column)

            if abs(contribution) < 1e-12:
                direction = "neutral"
            elif contribution > 0:
                direction = "positive"
            else:
                direction = "negative"

            contributions.append({
                "feature": column,
                "value": safe_number(raw_value) if isinstance(raw_value, (int, float, np.integer, np.floating)) else (str(raw_value) if raw_value is not None else None),
                "baselineValue": safe_number(baseline_value) if isinstance(baseline_value, (int, float, np.integer, np.floating)) else (str(baseline_value) if baseline_value is not None else None),
                "contribution": round(float(contribution), 6),
                "absoluteContribution": round(abs(float(contribution)), 6),
                "direction": direction,
            })

        contributions.sort(key=lambda item: item["absoluteContribution"], reverse=True)

        confidence = None
        probabilities = None
        if problem_type == "classification" and hasattr(pipeline, "predict_proba"):
            try:
                probs = pipeline.predict_proba(frame)[0]
                classes = getattr(pipeline.named_steps.get("model"), "classes_", [])
                probabilities = {
                    str(target_classes[int(c)]) if target_classes and str(c).isdigit() and int(c) < len(target_classes) else str(c):
                    safe_number(probs[i])
                    for i, c in enumerate(classes)
                }
                confidence = safe_number(float(np.max(probs)))
            except Exception:
                probabilities = None

        return {
            "success": True,
            "datasetId": dataset_id,
            "modelId": model_id,
            "targetColumn": metadata.get("targetColumn"),
            "problemType": problem_type,
            "algorithm": metadata.get("algorithm"),
            "prediction": prediction_label(prediction_raw),
            "confidence": confidence,
            "probabilities": probabilities,
            "baselinePrediction": safe_number(baseline_output),
            "predictionOutput": safe_number(full_output),
            "outputKind": output_kind,
            "contributions": contributions[:20],
            "globalFeatureImportance": metadata.get("featureImportance") or [],
            "method": "Baseline replacement contribution analysis",
            "notes": [
                "Positive contribution pushes the selected prediction/probability upward.",
                "Negative contribution pushes the selected prediction/probability downward.",
                "Contributions are local model explanations and should be interpreted with the model's evaluation metrics."
            ],
        }

    except HTTPException:
        raise
    except Exception as error:
        raise HTTPException(400, f"Explainability analysis failed: {error}")


