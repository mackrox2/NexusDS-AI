def is_numeric_series(series):















    converted = pd.to_numeric(















        series.astype(str).str.replace(",", "", regex=False).str.replace("%", "", regex=False).str.strip(),















        errors="coerce"















    )















    non_null = series.notna().sum()















    return non_null > 0 and converted.notna().sum() / non_null >= 0.80















































def numeric_convert(series):















    return pd.to_numeric(















        series.astype(str).str.replace(",", "", regex=False).str.replace("%", "", regex=False).str.strip(),















        errors="coerce"















    )















































def find_target_column(df, requested):















    requested = normalize_column_name(requested)































    if requested in df.columns:















        return requested































    for col in df.columns:















        if normalize_column_name(col).lower() == requested.lower():















            return col































    def compact(v):















        return normalize_column_name(v).lower().replace(" ", "").replace("_", "").replace("-", "")































    target = compact(requested)















    for col in df.columns:















        if compact(col) == target:















            return col































    raise HTTPException(















        400,















        f"Target column '{requested}' does not exist. Available columns: {[str(c) for c in df.columns]}"















    )















































def target_candidates(df):















    candidates = []















    n = max(len(df), 1)















    keywords = ("target", "label", "class", "outcome", "result", "status", "category", "approved", "price", "sales", "profit", "score")































    for col in df.columns:















        series = df[col]















        non_null = int(series.notna().sum())















        if non_null < 5:















            continue































        unique = int(series.dropna().nunique())















        unique_ratio = unique / max(non_null, 1)















        name = str(col).lower()































        score = 0















        reasons = []















        if any(k in name for k in keywords):















            score += 4















            reasons.append("column name suggests an outcome/target")















        if unique == 2:















            score += 3















            reasons.append("binary target")















        elif 2 < unique <= min(20, max(2, int(n * 0.1))):















            score += 2















            reasons.append("manageable number of classes")















        if is_numeric_series(series):















            score += 1















            reasons.append("numeric values can support regression")















        if unique_ratio > 0.8:















            score -= 4















            reasons.append("very high cardinality")































        candidates.append({















            "column": str(col),















            "kind": "numeric" if is_numeric_series(series) else "categorical",















            "uniqueValues": unique,















            "score": score,















            "reason": "; ".join(reasons) if reasons else "usable candidate based on data availability"















        })































    return sorted(candidates, key=lambda x: x["score"], reverse=True)[:8]















































